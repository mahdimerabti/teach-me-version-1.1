/**
 * Centralized Security Utilities for Teach Me
 * - Strict URL scheme validation (prevents javascript:, data:, vbscript:, file: XSS)
 * - Safe upload MIME & file extension allowlisting
 * - UUID & PostgREST filter validation
 * - Sensitive token/PII log redaction
 */

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function isValidUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID_REGEX.test(value.trim());
}

/**
 * Validates that an external URL uses HTTPS (or localhost HTTP during local development).
 * Rejects javascript:, data:, vbscript:, file:, and malformed URLs.
 */
export function sanitizeExternalUrl(rawUrl: string | null | undefined): string | null {
  if (!rawUrl || typeof rawUrl !== 'string') return null;
  const trimmed = rawUrl.trim();
  if (!trimmed) return null;

  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol === 'https:') {
      return parsed.toString();
    }
    if (
      import.meta.env.DEV &&
      parsed.protocol === 'http:' &&
      (parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1')
    ) {
      return parsed.toString();
    }
    return null;
  } catch {
    return null;
  }
}

/**
 * Validates media URLs (HTTPS, or local blob: object URLs generated by File preview).
 */
export function sanitizeMediaUrl(rawUrl: string | null | undefined): string | null {
  if (!rawUrl || typeof rawUrl !== 'string') return null;
  const trimmed = rawUrl.trim();
  if (trimmed.startsWith('blob:')) {
    return trimmed;
  }
  return sanitizeExternalUrl(trimmed);
}

/**
 * Normalizes and validates uploaded file extensions against an explicit allowlist.
 * Prevents .html, .svg, or path-traversal extension tricks in storage buckets.
 */
export function getSafeUploadExtension(
  fileName: string,
  allowedExtensions: readonly string[],
  fallbackExtension: string
): string {
  const parts = String(fileName || '').toLowerCase().split('.');
  const rawExt = parts.length > 1 ? parts.pop() || '' : '';
  const cleaned = rawExt.replace(/[^a-z0-9]/g, '');
  if (allowedExtensions.includes(cleaned)) {
    return cleaned;
  }
  return fallbackExtension;
}

/**
 * Validates password strength for new registrations and password changes:
 * - Minimum 8 characters, maximum 128 characters
 * - Contains at least one letter (Latin or Arabic) and one digit
 */
export function validatePasswordStrength(password: string): { valid: boolean; reason?: 'short' | 'long' | 'weak' } {
  if (typeof password !== 'string' || password.length < 8) {
    return { valid: false, reason: 'short' };
  }
  if (password.length > 128) {
    return { valid: false, reason: 'long' };
  }
  const hasLetter = /[a-zA-Z\u0600-\u06FF]/.test(password);
  const hasDigit = /\d/.test(password);
  if (!hasLetter || !hasDigit) {
    return { valid: false, reason: 'weak' };
  }
  return { valid: true };
}

/**
 * Redacts OAuth codes, JWTs, access/refresh tokens, and API keys from log strings.
 */
export function redactSensitiveText(input: string): string {
  if (!input) return '';
  return input
    .replace(/((?:access_token|refresh_token|provider_token|id_token|code|apikey|token)=)[^&#\s]+/gi, '$1[REDACTED]')
    .replace(/(Bearer\s+)[A-Za-z0-9._~+/-]+=*/gi, '$1[REDACTED]')
    .replace(/\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b/g, '[REDACTED_JWT]');
}
